"""Задержки повторов.

Три механизма повторов из RFC §6 независимы, и их задержки — разные константы.
Совпадение значений не подразумевается: смешение webhook и очередей повторов
уже было источником ошибки в дизайне.
"""

#: Задержки очередей повторов обработки сообщения, секунды (RFC §6.3).
#: Живут здесь, а не в инфраструктуре, чтобы соседство с webhook_backoff
#: было видно глазами.
RETRY_QUEUE_DELAYS: tuple[int, ...] = (2, 4, 8)


#: Задержка перед второй попыткой доставки webhook, секунды.
WEBHOOK_BASE_DELAY = 1.0


def webhook_backoff(attempt: int) -> float:
    """Задержка перед попыткой `attempt + 1` доставки webhook, секунды (RFC §6.2)."""
    return WEBHOOK_BASE_DELAY * 2 ** (attempt - 1)
